-- Supabase PostgreSQL schema for the dispatch API.
-- Existing Supabase projects already have these tables; CREATE IF NOT EXISTS
-- keeps the local db:init command safe for a fresh project as well.

CREATE TABLE IF NOT EXISTS public.users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account BIGINT NOT NULL UNIQUE,
  username TEXT NOT NULL UNIQUE,
  password TEXT NOT NULL,
  group_label TEXT,
  supervisor BOOLEAN NOT NULL DEFAULT FALSE,
  group_unruled TEXT
);

CREATE TABLE IF NOT EXISTS public.work_orders (
  id TEXT PRIMARY KEY,
  payload TEXT NOT NULL,
  updated_at DOUBLE PRECISION NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS work_orders_updated_at_idx
  ON public.work_orders (updated_at DESC);

ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.work_orders ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.users, public.work_orders FROM anon, authenticated, service_role;
REVOKE ALL ON SEQUENCE public.users_id_seq FROM anon, authenticated, service_role;
